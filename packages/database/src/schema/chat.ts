import {
  boolean,
  index,
  integer,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";

/*
 * Chat storage with field-level encryption (envelope scheme):
 * - each chat gets a random data key (DEK), stored wrapped by a master key
 *   (`dek_wrapped`, wrapped under master key `dek_key_id`);
 * - `title_enc`, `messages.content_enc` and `messages.reasoning_enc` are AES-256-GCM ciphertext under the DEK,
 *   with the row id as associated data so ciphertext can't be moved between rows.
 * Encryption happens in the AI service (apps/ai/app/core/crypto.py).
 * Rotating the master key only re-wraps DEKs; message rows stay untouched.
 *
 * IDs are generated by the client (same UUIDs as the browser's IndexedDB) so
 * saves are idempotent.
 */

export const messageRole = pgEnum("message_role", [
  "system",
  "user",
  "assistant",
]);
export const messageStatus = pgEnum("message_status", [
  "done",
  "stopped",
  "error",
]);

const timestamps = {
  createdAt: timestamp("created_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
};

export const chats = pgTable(
  "chats",
  {
    id: uuid().primaryKey(),
    /** Anonymous browser client id until auth exists; becomes the user id. */
    ownerId: uuid("owner_id").notNull(),
    titleEnc: text("title_enc").notNull(),
    model: text().notNull(),
    dekWrapped: text("dek_wrapped").notNull(),
    dekKeyId: text("dek_key_id").notNull(),
    ...timestamps,
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [index("chats_owner_updated_idx").on(t.ownerId, t.updatedAt)],
);

export const messages = pgTable(
  "messages",
  {
    id: uuid().primaryKey(),
    chatId: uuid("chat_id")
      .notNull()
      .references(() => chats.id, { onDelete: "cascade" }),
    role: messageRole().notNull(),
    status: messageStatus().notNull(),
    contentEnc: text("content_enc").notNull(),
    /** Model reasoning ("thinking") for assistant messages, encrypted like content. */
    reasoningEnc: text("reasoning_enc"),
    /** True when the user turned on deep thinking for this reply. */
    thinking: boolean().notNull().default(false),
    reasoningMs: integer("reasoning_ms"),
    /** True when the reply used web search (RAG). */
    webSearch: boolean("web_search").notNull().default(false),
    /** Encrypted JSON array of cited sources: [{ index, title, url, domain, snippet }]. */
    sourcesEnc: text("sources_enc"),
    /** Encrypted JSON array of image results (SearXNG): [{ url, thumbnail_url, title, source_url, width, height }]. */
    imagesEnc: text("images_enc"),
    /** Model that produced an assistant message. */
    model: text(),
    error: text(),
    promptTokens: integer("prompt_tokens"),
    completionTokens: integer("completion_tokens"),
    latencyMs: integer("latency_ms"),
    ...timestamps,
  },
  (t) => [index("messages_chat_created_idx").on(t.chatId, t.createdAt)],
);
