"""
Resumable completions (like ChatGPT): a reply is generated by a background
task, not by the HTTP request, so a refresh or dropped connection doesn't stop it.

Every SSE event is appended to a Redis stream `run:{id}:events` (id = the
assistant message id). Clients read the stream from the start and follow it
live, so reconnecting just replays and continues. Runs and their events
expire RUN_TTL_SECONDS after they finish. Stopping is an explicit call.

A heartbeat key (`run:{id}:alive`) lets readers notice a run that died with
the process (e.g. a server restart), instead of waiting forever.
"""

from __future__ import annotations

import asyncio
import json
import logging
from collections.abc import AsyncIterator
from uuid import UUID

from app.core.redis import redis_service

logger = logging.getLogger(__name__)

RUN_TTL_SECONDS = 3600
_ALIVE_SECONDS = 30
_READ_BLOCK_MS = 15_000
_END = "__end__"

# Runs started by this process, so they can be stopped.
_tasks: dict[UUID, asyncio.Task[None]] = {}


def _events_key(run_id: UUID) -> str:
    return f"run:{run_id}:events"


def _owner_key(run_id: UUID) -> str:
    return f"run:{run_id}:owner"


def _alive_key(run_id: UUID) -> str:
    return f"run:{run_id}:alive"


async def run_owner(run_id: UUID) -> UUID | None:
    owner = await redis_service.client.get(_owner_key(run_id))
    return UUID(owner) if owner else None


async def start_run(run_id: UUID, owner_id: UUID, events: AsyncIterator[str]) -> bool:
    """Start generating in the background. False if this run already exists
    (e.g. the request was retried), in which case callers just read it."""
    redis = redis_service.client
    if not await redis.set(_owner_key(run_id), str(owner_id), nx=True, ex=RUN_TTL_SECONDS):
        await events.aclose()  # type: ignore[attr-defined]
        return False
    await redis.set(_alive_key(run_id), "1", ex=_ALIVE_SECONDS)
    task = asyncio.create_task(_pump(run_id, events))
    _tasks[run_id] = task
    task.add_done_callback(lambda _: _tasks.pop(run_id, None))
    return True


async def _heartbeat(run_id: UUID) -> None:
    while True:
        await asyncio.sleep(_ALIVE_SECONDS / 3)
        await redis_service.client.set(_alive_key(run_id), "1", ex=_ALIVE_SECONDS)


async def _pump(run_id: UUID, events: AsyncIterator[str]) -> None:
    redis = redis_service.client
    key = _events_key(run_id)
    heartbeat = asyncio.create_task(_heartbeat(run_id))
    try:
        async for chunk in events:
            # Generators yield SSE frames ("data: {...}\n\n"); store the JSON.
            await redis.xadd(key, {"e": chunk.removeprefix("data: ").strip()})
    except asyncio.CancelledError:
        # Stopped by the user; the generator saved the partial reply.
        await redis.xadd(key, {"e": json.dumps({"type": "stopped"})})
    except Exception:
        logger.exception("Run %s failed", run_id)
        await redis.xadd(key, {"e": json.dumps({"type": "error", "message": "The model request failed."})})
    finally:
        heartbeat.cancel()
        await redis.xadd(key, {"e": _END})
        for k in (key, _owner_key(run_id)):
            await redis.expire(k, RUN_TTL_SECONDS)
        await redis.delete(_alive_key(run_id))


def stop_run(run_id: UUID) -> bool:
    task = _tasks.get(run_id)
    if task is None or task.done():
        return False
    task.cancel()
    return True


async def read_run(run_id: UUID, after: str = "0-0") -> AsyncIterator[str]:
    """SSE frames of a run from `after` (start by default), following it live."""
    redis = redis_service.client
    key = _events_key(run_id)
    last = after
    while True:
        response = await redis.xread({key: last}, block=_READ_BLOCK_MS, count=200)
        if not response:
            if not await redis.exists(_alive_key(run_id)):
                # Finished and expired, or the process running it died.
                if not await redis.exists(key):
                    yield f"data: {json.dumps({'type': 'error', 'message': 'This reply is no longer available.'})}\n\n"
                    return
                # Check once more for events written just before it ended.
                if not await redis.xread({key: last}, count=1):
                    yield f"data: {json.dumps({'type': 'error', 'message': 'The reply was interrupted.'})}\n\n"
                    return
                continue
            yield ": keep-alive\n\n"
            continue
        for _, entries in response:
            for entry_id, fields in entries:
                last = entry_id
                if fields["e"] == _END:
                    return
                yield f"id: {entry_id}\ndata: {fields['e']}\n\n"
